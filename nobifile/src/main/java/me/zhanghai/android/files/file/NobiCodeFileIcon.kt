 * NobiCode file icons, ported from NobiIDE's FileIconProvider (Sam's own
 * editor). File names are matched first, then extensions. Unknown files fall
 * back to the MIME-type icon so images, videos and archives keep their
 * generic icons. Name-based only: no file I/O, so resolving an icon never
 * slows down listing a folder.
 */

